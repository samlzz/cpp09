int main(int argc, char **argv)
{
	try
	{
		BitcoinExchange btc;

		btc.loadDatabase("assets/data.csv");
		btc.processInput(argc > 1 ? argv[1] : "");
	}
	catch (const std::exception &e)
	{
		std::cerr << "Error: " << e.what() << std::endl;
		return 1;
	}

	return 0;
}

